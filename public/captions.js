const PIPED_APIS = [
  "https://pipedapi.ducks.party",
  "https://api.piped.private.coffee",
];

const VIDEO_ID = /^[a-zA-Z0-9_-]{11}$/;

let streamCache = null;

function extractVideoId(input) {
  const value = String(input || "").trim();
  if (VIDEO_ID.test(value)) return value;

  let url;
  try {
    url = new URL(value);
  } catch {
    return null;
  }

  const host = url.hostname.toLowerCase().replace(/^www\./, "");
  const isYouTube =
    host === "youtu.be" ||
    host.endsWith(".youtube.com") ||
    host === "youtube.com" ||
    host.endsWith("youtube-nocookie.com");
  if (!isYouTube) return null;

  if (host === "youtu.be") {
    const id = url.pathname.split("/").filter(Boolean)[0] || "";
    return VIDEO_ID.test(id) ? id : null;
  }

  const fromQuery = url.searchParams.get("v");
  if (fromQuery && VIDEO_ID.test(fromQuery)) return fromQuery;

  const parts = url.pathname.split("/").filter(Boolean);
  const markers = new Set(["shorts", "embed", "live", "v"]);
  for (let i = 0; i < parts.length; i += 1) {
    const id = parts[i + 1];
    if (markers.has(parts[i]) && id && VIDEO_ID.test(id)) return id;
  }
  return null;
}

function rank(track) {
  const english = track.code === "en" || track.code.startsWith("en-") ? 0 : 2;
  return english + (track.isAutoGenerated ? 1 : 0);
}

function labelFor(subtitle) {
  const name = subtitle.name || subtitle.code || "Unknown";
  if (subtitle.autoGenerated && !/auto/i.test(name)) return `${name} (auto-generated)`;
  return name;
}

function describeSubtitles(subtitles) {
  return subtitles.map((subtitle, index) => ({
    id: `${index}:${subtitle.code || "und"}:${subtitle.autoGenerated ? "asr" : "manual"}`,
    code: subtitle.code || "",
    name: labelFor(subtitle),
    isAutoGenerated: Boolean(subtitle.autoGenerated),
    url: subtitle.url,
  }));
}

function pickTrack(tracks, requestedId) {
  if (requestedId) return tracks.find((track) => track.id === requestedId) || null;
  return [...tracks].sort((a, b) => rank(a) - rank(b) || a.name.localeCompare(b.name))[0] || null;
}

function decodeHtml(value) {
  return value
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&");
}

function captionText(inner) {
  return decodeHtml(inner.replace(/<br\s*\/?>/gi, " ").replace(/<[^>]+>/g, " "))
    .replace(/\s+/g, " ")
    .trim();
}

function parseClock(value) {
  const raw = String(value || "").trim();
  if (!raw) return 0;
  if (raw.endsWith("ms")) return parseFloat(raw) / 1000;
  if (raw.endsWith("s")) return parseFloat(raw);
  const parts = raw.split(":");
  if (parts.length === 3) return Number(parts[0]) * 3600 + Number(parts[1]) * 60 + Number(parts[2]);
  if (parts.length === 2) return Number(parts[0]) * 60 + Number(parts[1]);
  return Number(raw) || 0;
}

function dedupe(segments) {
  const cleaned = [];
  for (const segment of segments) {
    const text = segment.text.replace(/\s+/g, " ").trim();
    if (!text) continue;
    const previous = cleaned[cleaned.length - 1];
    if (previous && previous.text === text) continue;
    cleaned.push({
      text,
      start: Math.max(0, Number(segment.start) || 0),
      duration: Math.max(0, Number(segment.duration) || 0),
    });
  }
  return cleaned;
}

function parseXml(xml) {
  const segments = [];
  for (const match of xml.matchAll(/<p\b([^>]*)>([\s\S]*?)<\/p>/g)) {
    const attrs = match[1];
    const text = captionText(match[2]);
    if (!text) continue;
    if (/\bbegin=/.test(attrs)) {
      const start = parseClock(attrs.match(/\bbegin="([^"]+)"/)?.[1]);
      const end = parseClock(attrs.match(/\bend="([^"]+)"/)?.[1]);
      segments.push({ text, start, duration: Math.max(0, end - start) });
      continue;
    }
    const start = Number(attrs.match(/\bt="(\d+(?:\.\d+)?)"/)?.[1] ?? 0) / 1000;
    const duration = Number(attrs.match(/\bd="(\d+(?:\.\d+)?)"/)?.[1] ?? 0) / 1000;
    segments.push({ text, start, duration });
  }
  return dedupe(segments);
}

function parseVtt(text) {
  const segments = [];
  for (const block of text.split(/\n{2,}/)) {
    const lines = block.split(/\n/).map((line) => line.trim()).filter(Boolean);
    const timingIndex = lines.findIndex((line) => line.includes("-->"));
    if (timingIndex === -1) continue;
    const [startRaw, endRaw] = lines[timingIndex].split("-->");
    const textLine = captionText(lines.slice(timingIndex + 1).join(" "));
    if (!textLine) continue;
    const start = parseClock(startRaw.trim().split(" ")[0]);
    const end = parseClock((endRaw || "").trim().split(" ")[0]);
    segments.push({ text: textLine, start, duration: Math.max(0, end - start) });
  }
  return dedupe(segments);
}

function parseCaptionBody(body) {
  const trimmed = String(body || "").replace(/^\uFEFF/, "").trim();
  if (!trimmed || trimmed.startsWith("<html") || trimmed.startsWith("<!DOCTYPE")) return [];
  if (trimmed.startsWith("WEBVTT") || trimmed.includes("-->")) return parseVtt(trimmed);
  if (trimmed.startsWith("<")) return parseXml(trimmed);
  return [];
}

function allowedCaptionHost(apiBase, captionUrl) {
  const apiHost = new URL(apiBase).hostname.replace(/^(www\.|api\.|pipedapi\.)/, "");
  const captionHost = new URL(captionUrl, apiBase).hostname;
  return captionHost === apiHost || captionHost.endsWith(`.${apiHost}`);
}

async function fetchStreams(api, videoId) {
  const response = await fetch(`${api}/streams/${videoId}`, {
    signal: AbortSignal.timeout(12000),
  });
  if (!response.ok) throw new Error(String(response.status));
  const data = await response.json();
  if (!data || typeof data !== "object" || !data.title) {
    throw new Error(data?.error || "This video is unavailable.");
  }
  return { api, data };
}

async function loadStreams(videoId) {
  if (streamCache?.videoId === videoId) return streamCache;

  try {
    const result = await Promise.any(PIPED_APIS.map((api) => fetchStreams(api, videoId)));
    streamCache = { videoId, ...result };
    return streamCache;
  } catch {
    throw new Error("Couldn’t reach a captions server. Try again in a moment.");
  }
}

async function fetchTranscriptInBrowser(input, trackId) {
  const videoId = extractVideoId(input);
  if (!videoId) throw new Error("That doesn’t look like a YouTube link.");

  const { api, data } = await loadStreams(videoId);
  const listed = describeSubtitles(Array.isArray(data.subtitles) ? data.subtitles : []);
  if (listed.length === 0) throw new Error("This video doesn’t have captions.");

  const selected = pickTrack(listed, trackId ? String(trackId) : "");
  if (!selected) throw new Error("That caption language isn’t available for this video.");
  if (!selected.url || !allowedCaptionHost(api, selected.url)) {
    throw new Error("The captions server returned an unexpected address.");
  }

  const captionUrl = new URL(selected.url, api);
  const response = await fetch(captionUrl, { signal: AbortSignal.timeout(20000) });
  if (!response.ok) throw new Error("Couldn’t download the captions for this video.");
  const segments = parseCaptionBody(await response.text());
  if (segments.length === 0) {
    throw new Error("YouTube didn’t return the caption text for this video. It may be restricted.");
  }

  const tracks = listed
    .map(({ id, code, name, isAutoGenerated }) => ({ id, code, name, isAutoGenerated }))
    .sort((a, b) => rank(a) - rank(b) || a.name.localeCompare(b.name));

  return {
    videoId,
    title: data.title || "Untitled video",
    author: data.uploader || "",
    lengthSeconds: Number(data.duration) || null,
    thumbnail: `https://i.ytimg.com/vi/${videoId}/hq720.jpg`,
    watchUrl: `https://www.youtube.com/watch?v=${videoId}`,
    track: {
      id: selected.id,
      code: selected.code,
      name: selected.name,
      isAutoGenerated: selected.isAutoGenerated,
    },
    tracks,
    segments,
  };
}

window.fetchTranscriptInBrowser = fetchTranscriptInBrowser;
